#!/usr/bin/env python3
"""Build web/public/sprite.svg from icons/manifest.yaml.

OpenMoji sources are fetched (with --fetch) from the pinned npm release on jsDelivr into icons/openmoji/<CODE>.svg and
committed. Each one is transformed for the "cast-iron diner" look: every stroke-width x1.7 (chunkier outlines),
black recoloured to ink #1F1A17, ids namespaced per symbol. The output is deterministic (sorted by id).
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys
import urllib.request

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
OPENMOJI = 'https://cdn.jsdelivr.net/npm/openmoji@17.0.0/color/svg/{code}.svg'
SCALE = 1.7
INK = '#1F1A17'


def fetch(code: str) -> None:
    dest = ROOT / 'icons/openmoji' / f'{code}.svg'
    if dest.exists():
        return
    with urllib.request.urlopen(OPENMOJI.format(code=code), timeout=20) as r:
        dest.write_bytes(r.read())


def transform(svg: str, sym_id: str) -> tuple[str, str]:
    view_box = re.search(r'viewBox="([^"]+)"', svg).group(1)
    inner = re.sub(r'^.*?<svg[^>]*>(.*)</svg>\s*$', r'\1', svg, flags=re.S)
    inner = re.sub(r'stroke-width="([\d.]+)"', lambda m: f'stroke-width="{round(float(m.group(1)) * SCALE, 2):g}"', inner)
    inner = re.sub(r'#000000\b|#000(?=")|"black"', lambda m: f'"{INK}"' if m.group(0) == '"black"' else INK, inner)
    # namespace inner ids (and their references) so symbols never collide
    ids = re.findall(r'\sid="([^"]+)"', inner)
    for old in ids:
        new = f'{sym_id}-{old}'
        inner = inner.replace(f'id="{old}"', f'id="{new}"').replace(f'url(#{old})', f'url(#{new})') \
                     .replace(f'href="#{old}"', f'href="#{new}"')
    # OpenMoji wraps everything in <g id="color"> / <g id="line">: those ids carry no meaning, drop them
    inner = re.sub(rf'\sid="{re.escape(sym_id)}-(emoji|color|line|hair|skin|skin-shadow|line-supplement)"', '', inner)
    return view_box, re.sub(r'>\s+<', '><', inner.strip())


def catalogue_icons() -> dict[str, dict[str, str]]:
    """Every `icon:` used by catalogue/ and knowhow/ -> its sprite id: 'om:1F969' -> om-1f969, 'c:mince' -> c-mince."""
    found: dict[str, dict[str, str]] = {}

    def walk(node):
        if isinstance(node, dict):
            ref = node.get('icon')
            if isinstance(ref, str) and ref.startswith('om:'):
                found['om-' + ref[3:].lower()] = {'openmoji': ref[3:]}
            elif isinstance(ref, str) and ref.startswith('c:'):
                found['c-' + ref[2:]] = {'custom': ref[2:] + '.svg'}
            refs = node.get('icons')
            for r in refs if isinstance(refs, list) else []:
                if isinstance(r, str) and r.startswith('om:'):
                    found['om-' + r[3:].lower()] = {'openmoji': r[3:]}
            for v in node.values():
                walk(v)
        elif isinstance(node, list):
            for v in node:
                walk(v)
    for path in sorted((ROOT / 'catalogue').rglob('*.yaml')) + sorted((ROOT / 'knowhow').glob('*.yaml')):
        walk(yaml.safe_load(path.read_text()))
    return found


# The Browse overlay runs on third-party sites and can't <use> our sprite cross-origin: it gets these few icons inline
# (web/src/overlay/icons.json, same processing as the sprite).
OVERLAY_ICONS = ('home', 'back', 'save', 'language', 'checkmark')


def build(fetch_missing: bool, symbols: dict | None = None) -> str:
    manifest = yaml.safe_load((ROOT / 'icons/manifest.yaml').read_text())['icons']
    manifest = {**catalogue_icons(), **manifest}
    parts = []
    for key in sorted(manifest):
        src = manifest[key]
        sym_id = f'i-{key}'
        if 'openmoji' in src:
            if fetch_missing:
                fetch(str(src['openmoji']))
            svg = (ROOT / 'icons/openmoji' / f"{src['openmoji']}.svg").read_text()
        else:
            svg = (ROOT / 'icons/custom' / src['custom']).read_text()
        view_box, inner = transform(svg, sym_id)
        if symbols is not None:
            symbols[key] = {'viewBox': view_box, 'body': inner}
        parts.append(f'<symbol id="{sym_id}" viewBox="{view_box}">{inner}</symbol>')
    return ('<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n'
            '<!-- Generated by icons/build_sprite.py — do not edit. OpenMoji (CC BY-SA 4.0), thickened x1.7. -->\n'
            + '\n'.join(parts) + '\n</svg>\n')


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--fetch', action='store_true', help='download missing OpenMoji sources first')
    args = ap.parse_args()
    out = ROOT / 'web/public/sprite.svg'
    out.parent.mkdir(parents=True, exist_ok=True)
    symbols: dict = {}
    out.write_text(build(args.fetch, symbols))
    print(f'wrote {out} ({out.stat().st_size} bytes)')
    icons = ROOT / 'web/src/overlay/icons.json'
    icons.parent.mkdir(parents=True, exist_ok=True)
    icons.write_text(json.dumps({k: symbols[k] for k in OVERLAY_ICONS}, ensure_ascii=False, indent=1) + '\n')
    print(f'wrote {icons} ({icons.stat().st_size} bytes)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
